import io
import time
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


from backend.app.volumes import evaluate_longitudinal_assessment


def generate_comparison_pdf_report(comparison_data: Dict[str, Any]) -> bytes:
    """
    Generates a structured research PDF report documenting the longitudinal MRI comparison.
    Uses neutral research wording and includes mandatory prototype disclaimers.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#2B0E11")
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#6B5B5D")
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#854D0E")
    )
    section_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#2B0E11")
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#1F2937")
    )
    table_cell = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11
    )
    table_cell_bold = ParagraphStyle(
        "TableCellBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11
    )

    story = []

    # Title & Metadata
    story.append(Paragraph("NeuroScope 3D — Longitudinal Tumour Change Tracker", title_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph("Research and Educational Evaluation Report", subtitle_style))
    story.append(Spacer(1, 10))

    # Mandatory Disclaimer Banner
    disc_text = (
        "<b>PROTOTYPE DISCLAIMER:</b> This report is generated by a research and educational prototype. "
        "Estimated volumetric differences and model-predicted regions do NOT establish biological tumor growth, "
        "progression, or clinical response. Not for clinical diagnosis, patient management, or treatment decisions."
    )
    disc_table = Table([[Paragraph(disc_text, disclaimer_style)]], colWidths=[530])
    disc_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
        ('BOX', (0, 0), (-1, -1), 0.75, colors.HexColor("#F59E0B")),
        ('PADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(disc_table)
    story.append(Spacer(1, 12))

    # Longitudinal Assessment & Risk Box
    studies = comparison_data.get("studies", [])
    prev_study = next((s for s in studies if s.get("role") == "previous"), {})
    cur_study = next((s for s in studies if s.get("role") == "current"), {})

    assessment = comparison_data.get("assessment")
    if not assessment:
        assessment = evaluate_longitudinal_assessment(
            prev_study.get("volumes"), cur_study.get("volumes")
        )

    risk_lvl = assessment.get("riskLevel", "moderate")
    risk_colors = {
        "low": {"bg": "#ECFDF5", "border": "#10B981", "text": "#065F46"},
        "moderate": {"bg": "#EFF6FF", "border": "#3B82F6", "text": "#1E40AF"},
        "high": {"bg": "#FEF2F2", "border": "#EF4444", "text": "#991B1B"},
        "indeterminate": {"bg": "#F3F4F6", "border": "#9CA3AF", "text": "#374151"}
    }
    c_scheme = risk_colors.get(risk_lvl, risk_colors["moderate"])

    assess_style = ParagraphStyle(
        "AssessCallout",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor(c_scheme["text"])
    )
    assess_title_style = ParagraphStyle(
        "AssessTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=colors.HexColor(c_scheme["text"])
    )

    assess_content = [
        Paragraph(f"<b>STATUS:</b> {assessment.get('bettermentHeadline', 'Assessment Evaluated')}", assess_title_style),
        Spacer(1, 3),
        Paragraph(f"<b>RISK LEVEL:</b> {assessment.get('riskLabel', 'Moderate Risk')} | <b>BETTERMENT:</b> {'Yes (Volumetric Reduction)' if assessment.get('isImprovement') else 'No (Progression / Stable)'}", assess_title_style),
        Spacer(1, 4),
        Paragraph(assessment.get("summary", ""), assess_style),
        Spacer(1, 4),
        Paragraph(f"<i>Clinical Interpretation Note:</i> {assessment.get('clinicalInterpretation', '')}", assess_style),
    ]

    assess_table = Table([[assess_content]], colWidths=[530])
    assess_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor(c_scheme["bg"])),
        ('BOX', (0, 0), (-1, -1), 1.0, colors.HexColor(c_scheme["border"])),
        ('PADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(assess_table)
    story.append(Spacer(1, 12))

    # Comparison Context
    comp_id = comparison_data.get("comparison_id", "N/A")
    proc_at = comparison_data.get("processed_at", time.strftime("%Y-%m-%d %H:%M:%S"))
    meta_info = [
        [Paragraph(f"<b>Comparison ID:</b> {comp_id}", body_style), Paragraph(f"<b>Processed:</b> {proc_at}", body_style)],
        [Paragraph(f"<b>Model:</b> {comparison_data.get('model', {}).get('name', 'SegResNet')}", body_style),
         Paragraph(f"<b>Registration:</b> {comparison_data.get('registration', {}).get('method', 'SimpleITK Rigid3D')}", body_style)]
    ]
    meta_table = Table(meta_info, colWidths=[265, 265])
    meta_table.setStyle(TableStyle([('PADDING', (0, 0), (-1, -1), 3)]))
    story.append(meta_table)
    story.append(Spacer(1, 10))

    # Studies Overview
    story.append(Paragraph("Longitudinal Studies", section_style))
    story.append(Spacer(1, 4))
    
    study_rows = [
        [Paragraph("<b>Time Point</b>", table_cell_bold), Paragraph("<b>Label</b>", table_cell_bold), Paragraph("<b>Date</b>", table_cell_bold), Paragraph("<b>Segmentation Status</b>", table_cell_bold)],
        [Paragraph("Previous Study", table_cell), Paragraph(prev_study.get("label", "Baseline"), table_cell), Paragraph(prev_study.get("date", "—"), table_cell), Paragraph(prev_study.get("segmentation_status", "complete"), table_cell)],
        [Paragraph("Current Study", table_cell), Paragraph(cur_study.get("label", "Follow-up"), table_cell), Paragraph(cur_study.get("date", "—"), table_cell), Paragraph(cur_study.get("segmentation_status", "complete"), table_cell)],
    ]
    t_study = Table(study_rows, colWidths=[120, 160, 110, 140])
    t_study.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#F3F4F6")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ('PADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(t_study)
    story.append(Spacer(1, 12))

    # Volumetric Findings Table
    story.append(Paragraph("Estimated Volumetric Differences (Native Geometry)", section_style))
    story.append(Spacer(1, 4))

    vol_headers = [
        Paragraph("<b>Region</b>", table_cell_bold),
        Paragraph("<b>Previous (mL)</b>", table_cell_bold),
        Paragraph("<b>Current (mL)</b>", table_cell_bold),
        Paragraph("<b>Absolute Δ (mL)</b>", table_cell_bold),
        Paragraph("<b>Percentage Δ</b>", table_cell_bold)
    ]
    vol_rows = [vol_headers]

    region_names = {"WT": "Whole Tumour (WT)", "TC": "Tumour Core (TC)", "ET": "Enhancing Tumour (ET)"}
    prev_vols = prev_study.get("volumes", {}) or {}
    cur_vols = cur_study.get("volumes", {}) or {}

    for r in ["WT", "TC", "ET"]:
        p_val = prev_vols.get(r, {}).get("volumeMl", 0.0)
        c_val = cur_vols.get(r, {}).get("volumeMl", 0.0)
        abs_d = c_val - p_val
        
        if p_val == 0:
            pct_str = "Undefined (zero baseline)"
        else:
            pct = (abs_d / p_val) * 100.0
            pct_str = f"{'+' if pct > 0 else ''}{pct:.1f}%"

        vol_rows.append([
            Paragraph(region_names.get(r, r), table_cell),
            Paragraph(f"{p_val:.2f}", table_cell),
            Paragraph(f"{c_val:.2f}", table_cell),
            Paragraph(f"{'+' if abs_d > 0 else ''}{abs_d:.2f}", table_cell),
            Paragraph(pct_str, table_cell)
        ])

    t_vols = Table(vol_rows, colWidths=[170, 90, 90, 90, 90])
    t_vols.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#F3F4F6")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ('PADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(t_vols)
    story.append(Spacer(1, 14))

    # Registration Quality & Warnings
    story.append(Paragraph("Registration Quality & Methodological Limitations", section_style))
    story.append(Spacer(1, 4))
    
    reg_info = comparison_data.get("registration", {})
    reg_text = (
        f"<b>Registration Quality:</b> {reg_info.get('quality', 'pass').upper()}<br/>"
        f"<b>Transformation:</b> {reg_info.get('transform', 'N/A')}<br/>"
        f"<b>Metric Score (Mattes MI):</b> {reg_info.get('metrics', {}).get('mattes_mi', 'N/A')}<br/>"
    )
    story.append(Paragraph(reg_text, body_style))
    story.append(Spacer(1, 6))

    all_warnings = reg_info.get("warnings", []) + comparison_data.get("warnings", [])
    if all_warnings:
        warn_text = "<b>Noted Observations:</b><br/>" + "<br/>".join(f"• {w}" for w in all_warnings)
        story.append(Paragraph(warn_text, body_style))
    else:
        story.append(Paragraph("• No significant registration deviations or geometric anomalies detected.", body_style))

    doc.build(story)
    return buffer.getvalue()
